"""Render VALIDATION.md from computed metrics. No number in this file is a literal.

The document is generated on every run and overwritten in place. That is a rule with
a reason behind it: a validation document with hand-written numbers in it decays
silently, and the moment one figure in it is stale the whole document is worthless
because a reader cannot tell which one. Every quantity below arrives as an argument.
The prose is fixed and the numbers are not, so a regression shows up as a changed
number under unchanged prose rather than as a document nobody dares regenerate.
"""

